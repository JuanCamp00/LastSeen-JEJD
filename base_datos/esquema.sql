CREATE TABLE IF NOT EXISTS usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS acertijo (
    id_acertijo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta TEXT NOT NULL,
    orden INTEGER NOT NULL UNIQUE,
    tipo_validacion VARCHAR(12) NOT NULL,
    respuesta_correcta_texto TEXT
);

CREATE TABLE IF NOT EXISTS partida (
    id_partida INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMPTZ,
    tiempo_total_segundos INTEGER,
    estado VARCHAR(12) NOT NULL DEFAULT 'EN_CURSO',

    CONSTRAINT fk_partida_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario),

    CONSTRAINT chk_estado_partida
        CHECK (estado IN ('PENDIENTE', 'EN_CURSO', 'FINALIZADA')),

    CONSTRAINT chk_tiempo_partida
        CHECK (tiempo_total_segundos IS NULL OR tiempo_total_segundos >= 0)
);


CREATE TABLE IF NOT EXISTS partida_acertijo (
    id_partida INTEGER NOT NULL,
    id_acertijo INTEGER NOT NULL,
    estado VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE',
    fecha_resolucion TIMESTAMPTZ,

    CONSTRAINT pk_partida_acertijo
        PRIMARY KEY (id_partida, id_acertijo),

    CONSTRAINT fk_pa_partida
        FOREIGN KEY (id_partida)
        REFERENCES partida(id_partida),

    CONSTRAINT fk_pa_acertijo
        FOREIGN KEY (id_acertijo)
        REFERENCES acertijo(id_acertijo),

    CONSTRAINT chk_estado_acertijo
        CHECK (estado IN ('PENDIENTE', 'RESUELTO'))
);

CREATE TABLE IF NOT EXISTS opcion_acertijo (
    id_opcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_acertijo INTEGER NOT NULL,
    texto_opcion TEXT NOT NULL,
    orden INTEGER NOT NULL,
    es_correcta BOOLEAN NOT NULL,

    CONSTRAINT fk_opcion_acertijo
        FOREIGN KEY (id_acertijo)
        REFERENCES acertijo(id_acertijo)
);


CREATE TABLE IF NOT EXISTS intento (
    id_intento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_partida INTEGER NOT NULL,
    id_acertijo INTEGER NOT NULL,
    fecha_intento TIMESTAMPTZ NOT NULL,
    respuesta_texto TEXT,
    id_opcion_seleccionada INTEGER,
    resultado VARCHAR(12) NOT NULL,

    CONSTRAINT fk_intento_partida_acertijo
        FOREIGN KEY (id_partida, id_acertijo)
        REFERENCES partida_acertijo(id_partida, id_acertijo),

    CONSTRAINT fk_intento_opcion
        FOREIGN KEY (id_opcion_seleccionada)
        REFERENCES opcion_acertijo(id_opcion),

  CONSTRAINT chk_resultado_intento
    CHECK (resultado IN ('CORRECTO', 'INCORRECTO')),

CONSTRAINT chk_intento_modalidad_respuesta
    CHECK (
        (
            respuesta_texto IS NOT NULL
            AND BTRIM(respuesta_texto) <> ''
            AND id_opcion_seleccionada IS NULL
        )
        OR
        (
            respuesta_texto IS NULL
            AND id_opcion_seleccionada IS NOT NULL
        )
    )
);

CREATE TABLE IF NOT EXISTS pista (
    id_pista INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_acertijo INTEGER NOT NULL,
    contenido TEXT NOT NULL,
    orden INTEGER NOT NULL,
    disponible_desde_inicio BOOLEAN NOT NULL,

    CONSTRAINT fk_pista_acertijo
        FOREIGN KEY (id_acertijo)
        REFERENCES acertijo(id_acertijo)
);

CREATE TABLE IF NOT EXISTS partida_pista (
    id_partida INTEGER NOT NULL,
    id_pista INTEGER NOT NULL,
    desbloqueada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    guardada BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_guardado TIMESTAMPTZ,

    CONSTRAINT pk_partida_pista
        PRIMARY KEY (id_partida, id_pista),

    CONSTRAINT fk_pp_partida
        FOREIGN KEY (id_partida)
        REFERENCES partida(id_partida),

    CONSTRAINT fk_pp_pista
        FOREIGN KEY (id_pista)
        REFERENCES pista(id_pista)
);

CREATE TABLE IF NOT EXISTS contenido (
    id_contenido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_acertijo_desbloqueador INTEGER,
    titulo VARCHAR(120) NOT NULL,
    descripcion TEXT,
    tipo_contenido VARCHAR(16) NOT NULL,
    recurso TEXT NOT NULL,

    CONSTRAINT fk_contenido_acertijo
        FOREIGN KEY (id_acertijo_desbloqueador)
        REFERENCES acertijo(id_acertijo)
);

CREATE TABLE IF NOT EXISTS partida_contenido (
    id_partida INTEGER NOT NULL,
    id_contenido INTEGER NOT NULL,
    desbloqueado_en TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_partida_contenido
        PRIMARY KEY (id_partida, id_contenido),

    CONSTRAINT fk_pc_partida
        FOREIGN KEY (id_partida)
        REFERENCES partida(id_partida),

    CONSTRAINT fk_pc_contenido
        FOREIGN KEY (id_contenido)
        REFERENCES contenido(id_contenido)
);

CREATE TABLE IF NOT EXISTS progreso (
    id_progreso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_partida INTEGER NOT NULL UNIQUE,
    id_acertijo_actual INTEGER,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_progreso_partida
        FOREIGN KEY (id_partida)
        REFERENCES partida(id_partida),

    CONSTRAINT fk_progreso_acertijo_actual
        FOREIGN KEY (id_partida, id_acertijo_actual)
        REFERENCES partida_acertijo(id_partida, id_acertijo)
);

CREATE TABLE IF NOT EXISTS resultado_ranking (
    id_resultado_ranking INTEGER
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_partida INTEGER NOT NULL UNIQUE,

    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_resultado_ranking_partida
        FOREIGN KEY (id_partida)
        REFERENCES partida(id_partida)
);



